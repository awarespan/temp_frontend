import React, { useState } from 'react';
import { useVolunteer } from '../context/VolunteerContext';
import { Shield, KeyRound, X, AlertCircle, CheckCircle2 } from 'lucide-react';

interface LoginModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const LoginModal: React.FC<LoginModalProps> = ({ isOpen, onClose }) => {
  const { login, config } = useVolunteer();
  const [operatorId, setOperatorId] = useState('operator-alpha');
  const [totpCode, setTotpCode] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [success, setSuccess] = useState(false);

  if (!isOpen) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setIsSubmitting(true);

    const result = await login(operatorId, totpCode);
    setIsSubmitting(false);

    if (result.success) {
      setSuccess(true);
      setTimeout(() => {
        setSuccess(false);
        setTotpCode('');
        onClose();
      }, 700);
    } else {
      setError(result.error || 'Authentication rejected.');
    }
  };

  const fillQuickCode = (code: string) => {
    setTotpCode(code);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 backdrop-blur-sm p-4">
      <div className="w-full max-w-md bg-[#000000] border border-[#3c3c3c] shadow-2xl relative">
        {/* Header bar */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-[#3c3c3c] bg-[#1a1a1a]">
          <div className="flex items-center gap-2">
            <Shield className="w-4 h-4 text-[#ff4f2b]" />
            <h2 className="font-mono text-sm uppercase tracking-wider text-[#f5f5f5]">
              OPERATOR AUTHENTICATION
            </h2>
          </div>
          <button
            onClick={onClose}
            className="text-[#737373] hover:text-[#f5f5f5] p-1 cursor-pointer transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Content */}
        <form onSubmit={handleSubmit} className="p-6 space-y-5">
          <p className="text-xs font-mono text-[#bfbfbf] leading-relaxed">
            Enter your Operator Identity and the 6-digit TOTP code generated by your
            authenticator application to request temporary volunteer streaming credentials.
          </p>

          {error && (
            <div className="p-3 bg-red-950/40 border border-red-800 text-red-300 text-xs font-mono flex items-start gap-2">
              <AlertCircle className="w-4 h-4 text-red-400 shrink-0 mt-0.5" />
              <div>{error}</div>
            </div>
          )}

          {success && (
            <div className="p-3 bg-emerald-950/40 border border-emerald-800 text-emerald-300 text-xs font-mono flex items-center gap-2">
              <CheckCircle2 className="w-4 h-4 text-emerald-400 shrink-0" />
              <div>Authenticated successfully. Session issued.</div>
            </div>
          )}

          <div>
            <label className="block text-xs font-mono uppercase text-[#bfbfbf] mb-1.5">
              Operator Identifier
            </label>
            <input
              type="text"
              value={operatorId}
              onChange={(e) => setOperatorId(e.target.value)}
              placeholder="e.g. operator-alpha"
              className="w-full bg-[#1a1a1a] border border-[#3c3c3c] focus:border-[#ff4f2b] px-3 py-2 text-sm font-mono text-[#f5f5f5] outline-none transition-colors"
              required
            />
          </div>

          <div>
            <div className="flex justify-between items-center mb-1.5">
              <label className="block text-xs font-mono uppercase text-[#bfbfbf]">
                TOTP 6-Digit Authenticator Code
              </label>
              <div className="flex items-center gap-1 text-[11px] font-mono text-[#737373]">
                <KeyRound className="w-3 h-3" />
                <span>Authenticator App</span>
              </div>
            </div>
            <input
              type="text"
              maxLength={6}
              value={totpCode}
              onChange={(e) => setTotpCode(e.target.value.replace(/\D/g, ''))}
              placeholder="123456"
              className="w-full bg-[#1a1a1a] border border-[#3c3c3c] focus:border-[#ff4f2b] px-3 py-2 text-lg font-mono text-center tracking-[0.35em] text-[#f5f5f5] outline-none transition-colors"
              autoFocus
              required
            />
          </div>

          {/* Quick test helpers for mock mode */}
          {config.mockMode && (
            <div className="pt-2 border-t border-[#1a1a1a]">
              <div className="text-[11px] font-mono text-[#737373] mb-1.5">
                MOCK MODE TEST HELPERS:
              </div>
              <div className="flex gap-2">
                <button
                  type="button"
                  onClick={() => fillQuickCode('123456')}
                  className="px-2 py-1 text-[11px] font-mono bg-[#1a1a1a] hover:bg-[#252525] border border-[#3c3c3c] text-[#bfbfbf] cursor-pointer"
                >
                  Valid Code (123456)
                </button>
                <button
                  type="button"
                  onClick={() => fillQuickCode('000000')}
                  className="px-2 py-1 text-[11px] font-mono bg-[#1a1a1a] hover:bg-[#252525] border border-[#3c3c3c] text-red-400 cursor-pointer"
                >
                  Reject Code (000000)
                </button>
              </div>
            </div>
          )}

          {/* Action buttons */}
          <div className="pt-4 flex items-center justify-end gap-3 border-t border-[#3c3c3c]">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2 text-xs font-mono uppercase text-[#bfbfbf] hover:text-[#f5f5f5] border border-[#3c3c3c] hover:border-[#bfbfbf] transition-colors cursor-pointer"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isSubmitting}
              className="px-5 py-2 text-xs font-mono uppercase font-semibold text-black bg-[#ff4f2b] hover:bg-[#e04523] disabled:opacity-50 transition-colors cursor-pointer"
            >
              {isSubmitting ? 'Verifying...' : 'Authenticate'}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
